function profile = getConformanceProfile(payload)
%GETCONFORMANCEPROFILE Classify only verified Core bytes; partial APIs fail closed.
record = jsondecode(fileread(fullfile(payload, 'payload-source.json')));
assert(strcmp(record.schema, 'wss-matlab-projection/v1') && ~record.bootstrap_reference, ...
    'A complete candidate projection is required.');
assert(strcmp(record.candidate.repository, 'cwru-non-academic/WSSCore'), 'Wrong payload producer.');
paths = {record.files.source};
expected = { ...
    'WSS_Core_Interface.dll'; ...
    'WSS.Transport.Serial.dll'; ...
    'WSS.Transport.BLE.dll'; ...
    'Newtonsoft.Json.dll'; ...
    'System.IO.Ports.dll'; ...
    'System.Memory.dll'; ...
    'System.Buffers.dll'; ...
    'System.Numerics.Vectors.dll'; ...
    'System.Runtime.CompilerServices.Unsafe.dll'; ...
    'System.Security.Permissions.dll'; ...
    'System.Security.AccessControl.dll'; ...
    'System.Security.Principal.Windows.dll'; ...
    'backends/windows/WSS.Transport.BLE.Windows.dll'; ...
    'backends/windows/WSS.Transport.BLE.Windows.Native.dll'; ...
    'backends/windows/WssBleWindows.dll'; ...
    'backends/macos/WSS.Transport.BLE.MacOS.dll'; ...
    'backends/macos/libwss_macos_ble.dylib'; ...
    'backends/linux/WSS.Transport.BLE.Linux.dll'; ...
    'backends/linux/Linux.Bluetooth.dll'; ...
    'backends/linux/Tmds.DBus.dll'; ...
    'backends/linux/Microsoft.Bcl.AsyncInterfaces.dll'; ...
    'backends/linux/System.Reflection.Emit.dll'; ...
    'backends/linux/System.Reflection.Emit.ILGeneration.dll'; ...
    'backends/linux/System.Threading.Tasks.Extensions.dll'; ...
    'runtimes/win/lib/net8.0/System.IO.Ports.dll'; ...
    'runtimes/unix/lib/net8.0/System.IO.Ports.dll'; ...
    'runtimes/linux-x64/native/libSystem.IO.Ports.Native.so'};
assert(isequal(sort(paths), sort(reshape(expected, 1, []))), 'Wrong projection inventory.');
inventory = dir(fullfile(payload, '**', '*'));
inventory = inventory(~[inventory.isdir]);
actual = cell(1, numel(inventory));
for k = 1:numel(inventory)
    file = fullfile(inventory(k).folder, inventory(k).name);
    actual{k} = strrep(char(System.IO.Path.GetRelativePath(payload, file)), '\', '/');
end
assert(isequal(sort(actual), sort([paths, {'payload-source.json'}])), 'Extra or missing projection files.');
assert(numel(paths) == 27 && numel(unique(paths)) == 27, 'Incomplete projection inventory.');
lines = cell(1, numel(paths));
for k = 1:numel(paths)
    relative = paths{k};
    assert(~startsWith(relative, '/') && isempty(regexp(relative, '(^|/)\.\.(/|$)|\\|:', 'once')), ...
        'Unsafe projection path.');
    file = fullfile(payload, relative);
    digest = hashBytes(System.IO.File.ReadAllBytes(file));
    assert(strcmp(digest, record.files(k).sha256), 'Projection file hash mismatch: %s', relative);
    lines{k} = [relative '|' digest];
end
assert(strcmp(hashBytes(unicode2native(strjoin(sort(lines), newline), 'UTF-8')), record.projection_sha256), ...
    'Projection digest mismatch.');
wss.loadRuntime(wss.WssConfig('CsLibDir', payload, 'ConformanceMode', true));
assembly = System.Reflection.Assembly.LoadFrom(fullfile(payload, 'WSS_Core_Interface.dll'));
assert(strcmp(hashBytes(System.IO.File.ReadAllBytes(char(assembly.Location))), ...
    record.files(strcmp(paths, 'WSS_Core_Interface.dll')).sha256), 'Loaded Core differs from verified payload.');
legacy = assembly.GetType('Wss.Testing.WssBehaviorScenarios');
baseline = false(1, 6);
names = {'NormalizedStimulation','Initialization','DirectAnalog','RuntimeEventEdit','StopStimulation','StimulationFixture'};
for k = 1:numel(names), baseline(k) = property(legacy, names{k}); end
catalog = assembly.GetType('Wss.Testing.WssStimulationSequences');
sequence = assembly.GetType('Wss.Testing.WssStimulationSequence');
step = assembly.GetType('Wss.Testing.WssStimulationStep');
window = assembly.GetType('Wss.Testing.WssStimulationWindow');
result = assembly.GetType('Wss.Testing.WssStimulationWindowResult');
snapshot = assembly.GetType('Wss.CoreModule.WssConfigurationSnapshot');
types = [~isempty(catalog), ~isempty(sequence), ~isempty(step), ~isempty(window), ~isempty(result), ~isempty(snapshot)];
modern = [property(catalog, 'SingleDevice'), property(catalog, 'MultipleDevices'), ...
    property(catalog, 'LayeredSingleDevice'), property(catalog, 'LayeredMultipleDevices'), ...
    method(sequence, 'WriteFixture'), property(step, 'Modeled'), property(step, 'ReloadParameters'), ...
    property(step, 'ReloadModel'), method(step, 'PrepareReload'), method(window, 'Evaluate'), ...
    property(result, 'Settled'), property(result, 'Passed'), property(result, 'Failures'), property(result, 'Diagnostics')];
name = classifyConformanceApi(baseline, types, modern);
profile = struct('name', name, 'candidate', record.candidate, 'projection_sha256', record.projection_sha256, 'core_sha256', record.files(strcmp(paths, 'WSS_Core_Interface.dll')).sha256);
end

function present = property(type, name)
present = ~isempty(type) && ~isempty(type.GetProperty(name));
end

function present = method(type, name)
present = ~isempty(type) && ~isempty(type.GetMethod(name));
end

function value = hashBytes(bytes)
algorithm = System.Security.Cryptography.SHA256.Create();
cleanup = onCleanup(@() algorithm.Dispose());
value = lower(reshape(dec2hex(uint8(algorithm.ComputeHash(uint8(bytes))), 2).', 1, []));
end
